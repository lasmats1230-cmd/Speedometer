android {
    namespace = "com.lasse.speedometer"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.lasse.speedometer"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("release") {
            // Supplied out of band via keystore.properties, which is not in
            // version control. Without it, release builds stay unsigned rather
            // than silently falling back to the debug key.
            val properties = Properties().apply {
                val file = rootProject.file("keystore.properties")
                if (file.exists()) file.inputStream().use { load(it) }
            }
            val storePath = properties.getProperty("storeFile")
            if (storePath != null) {
                storeFile = file(storePath)
                storePassword = properties.getProperty("storePassword")
                keyAlias = properties.getProperty("keyAlias")
                keyPassword = properties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8 matters more than usual here: material-icons-extended pulls in
            // a thousand icons of which this app uses about twenty.
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.getByName("release").storeFile?.let {
                signingConfig = signingConfigs.getByName("release")
            }
        }
        debug {
            applicationIdSuffix = ".debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        isCoreLibraryDesugaringEnabled = true
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    /**
     * MapLibre's renderer is native code, so a universal APK carries the same
     * ~13 MB library four times over. Per-ABI APKs keep an install to the one
     * architecture the phone can actually run; the universal APK stays around
     * for when it isn't obvious which that is.
     */
    splits {
        abi {
            isEnable = true
            reset()
            include("arm64-v8a", "armeabi-v7a", "x86_64")
            isUniversalApk = true
        }
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    testOptions {
        unitTests {
            // Robolectric renders the Compose screens in these tests, which
            // means it needs the real resources rather than stubs.
            isIncludeAndroidResources = true
        }
    }
}

